package org.javafn.utils;

import edu.umd.cs.findbugs.annotations.CheckReturnValue;

import java.util.Optional;
import java.util.function.BooleanSupplier;
import java.util.function.Supplier;

/**
 * <p>This class contains methods for expressing expectations that cannot be guaranteed by the compiler,
 * but which you the programmer are claiming are valid.  For example, if you have a pipeline of
 * {@link java.util.Optional}s, you filter on isPresent, but then later call get, but the compiler
 * fails to recognize it, you could instead use `orElseThrow(Expect.optionalPresent)`. Then later,
 * when you break this expectation, you'll get a helpful exception.
 * </p><p>
 * The exceptions generated by this class contain the suffix "this is likely a programming error"
 * so they should only be used when you are asserting that a certain condition shouldn't be reachable.
 * For error handling without throwing exceptions, see the Result class in the main javafn repository.
 * </p>
 */
public final class Expect {

    /**
     * A {@link Supplier} of {@link IllegalStateException}s with the {@link Supplier#get()} method overridden
     * with the {@link CheckReturnValue} annotation added, to help ensure the resulting exception is actually
     * thrown; i.e., methods that return an instance of this class do not throw the exception themselves.
     */
    public interface IllegalStateExceptionSupplier extends Supplier<IllegalStateException> {
        @CheckReturnValue IllegalStateException get();
    }

    /**
     * Return an IllegalStateException that can be thrown.
     * <pre>{@code
     * int oneOrZero = someFn() ? 1 : 0;
     * switch (oneOrZero) {
     *     case 1 -> ...;
     *     case 0 -> ...;
     *     default -> throw Expect.unmet("boolean to int would be 0 or 1");
     * }
     * }</pre>
     * The supplied expectation is embedded in the string
     * <pre>Expectation that [your expectation] was not met; this is likely a programming error.</pre>
     * @param expectation message describing the expectation
     * @return an IllegalStateException that should be thrown
     */
    @CheckReturnValue
    public static IllegalStateException unmet(final String expectation) {
        return new IllegalStateException("Expectation that " + expectation + " was not met; this is likely a programming error.");
    }

    /**
     * Return an {@link IllegalStateExceptionSupplier} that, when invoked, returns an exception that can be thrown.
     * This represents a deferred call to {@link Expect#unmet(String)}, useful when the exception
     * should not be immediately materialized
     * @param expectation the expectation that was unmet
     * @return a {@link IllegalStateExceptionSupplier} that returns an exception that should be thrown.
     */
    public static IllegalStateExceptionSupplier that(final String expectation) {
        return () -> unmet(expectation);
    }

    /**
     * Execute the supplied boolean supplier.  If it returns false, throw an exception returned
     * from {@link Expect#unmet(String)} with the supplied expectation that was unmet
     * @param fn a test condition
     * @param expectation the expectation that was not met if fn returns false
     */
    public static void that(final BooleanSupplier fn, final String expectation) {
        if (!fn.getAsBoolean()) throw unmet(expectation);
    }

    /**
     * Expectation that an optional's presence was already checked, useful as an argument to
     * `orElseThrow`, as in
     * <pre>{@code
     * var definitelyNotEmptyOpt = ...;
     * var v = definitelyNotEmptyOpt.orElseThrow(Expect.optionalPresent);
     * }</pre>
     * Use this when you know the optional cannot be empty, but the compiler doesn't know this
     * and warns you about an {@link Optional#get()} without {@link Optional#isPresent()}.
     * @return an {@link IllegalStateExceptionSupplier} that can be passed to {@link Optional#orElseThrow(Supplier)}
     */
    public static IllegalStateExceptionSupplier optionalPresent() {
        return () -> unmet("optional's presence was already checked");
    }

    /**
     * Throw an IllegalStateException if this constructor is called; to be used in the private
     * constructor of a class containing only static components.
     * @implNote always throws
     */
    public static void staticConstructorNotCalled() { staticConstructorNotCalled(null);}

    /**
     * Throw an IllegalStateException if this constructor is called; to be used in the private
     * constructor of a class containing only static components.
     * @param clazz the {@link Class} object that should not be constructed
     * @implNote always throws
     */
    public static void staticConstructorNotCalled(final Class<?> clazz) {
        throw unmet("%s static class cannot be instantiated"
                .formatted(clazz == null ? "This" : clazz.getCanonicalName()));
    }

    private Expect() { Expect.staticConstructorNotCalled(this.getClass()); }
}
